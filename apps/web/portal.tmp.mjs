import { chromium } from "playwright";
const S = process.argv[2];
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:3001/portal/login"); await p.waitForTimeout(800);
await p.screenshot({ path: `${S}/shots/login.png` });
await p.getByLabel("Correo", { exact: true }).fill("admin@codexai.com");
await p.getByLabel("Contraseña").fill("codex-admin-2026");
await p.getByRole("button", { name: "Ingresar" }).click();
await p.getByRole("heading", { name: /Hola/ }).waitFor({ timeout: 30000 });
await p.screenshot({ path: `${S}/shots/dash.png` });
await p.goto("http://localhost:3001/portal/cursos"); await p.waitForTimeout(500);
await p.getByPlaceholder("Título del curso nuevo").fill("Agentes de IA para negocios");
await p.getByRole("button", { name: "Crear curso" }).click();
await p.getByRole("heading", { name: "Agentes de IA para negocios" }).waitFor({ timeout: 30000 });
await p.getByPlaceholder("Nombre del módulo nuevo").fill("Fundamentos");
await p.getByRole("button", { name: "Agregar módulo" }).click();
await p.getByRole("button", { name: "Agregar lección" }).waitFor();
await p.getByRole("button", { name: "Agregar lección" }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${S}/shots/editor.png`, fullPage: true });
const id = p.url().split("/").pop();
await p.request.delete(`http://localhost:3001/api/portal/courses/${id}`);
console.log(errs.join("\n") || "no console errors");
await b.close();
